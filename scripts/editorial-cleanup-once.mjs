function cleanDescription(a) {
  const sentences = String(a.intro || '').match(/[^.!?]+[.!?]+/g) || [];
  let out = '';
  for (const raw of sentences) {
    const s = raw.trim();
    if (!s) continue;
    if ((out + ' ' + s).trim().length > 245) break;
    out = (out + ' ' + s).trim();
    if (out.length >= 110) break;
  }
  if (out.length >= 70) return out;
  const words = String(a.intro || a.title || '').trim().split(/\s+/);
  let short = '';
  for (const word of words) {
    if ((short + ' ' + word).trim().length > 215) break;
    short = (short + ' ' + word).trim();
  }
  return /[.!?]$/.test(short) ? short : short + '.';
}

