let changed = 0;
for (const name of readdirSync(ARTICLES_DIR).filter((n) => n.endsWith('.json'))) {
  const file = path.join(ARTICLES_DIR, name);
  const a = JSON.parse(readFileSync(file, 'utf8'));
  if (a.status !== 'published' || a.publishedAt !== TARGET_DATE) continue;
  let dirty = false;

  if (String(a.imageAlt || '').startsWith('Реалистичное тематическое фото:')) {
    a.imageAlt = makeAlt(a);
    dirty = true;
  }

  const desc = String(a.description || '');
  if (/\s[\p{L}]$/u.test(desc) || (desc.length >= 250 && !/[.!?…»)]$/.test(desc))) {
    a.description = cleanDescription(a);
    dirty = true;
  }

  for (const section of a.sections || []) {
    if (!Array.isArray(section.paragraphs)) continue;
    if (section.paragraphs.includes(badConclusion1) || section.paragraphs.includes(badConclusion2)) {
      section.paragraphs = makeConclusion(a);
      dirty = true;
    }
  }

  if (dirty) {
    writeFileSync(file, JSON.stringify(a, null, 2) + '\n');
    console.log('[cleanup] improved', a.slug);
    changed++;
  }
}

const workflowPath = '.github/workflows/build-site.yml';
let workflow = readFileSync(workflowPath, 'utf8');
if (!workflow.includes('Editorial quality guard')) {
  const marker = '      - name: Validate and generate\n';
  const guard = '      - name: Editorial quality guard\n        run: |\n          node --check scripts/editorial-quality-check.mjs\n          node scripts/editorial-quality-check.mjs\n';
  if (!workflow.includes(marker)) throw new Error('build workflow insertion marker not found');
  workflow = workflow.replace(marker, guard + marker);
  writeFileSync(workflowPath, workflow);
  console.log('[cleanup] installed permanent editorial quality guard');
}

